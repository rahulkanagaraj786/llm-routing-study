def footer(fig, text):
    text = (TAG + ". " if TAG else "") + text
    width = int(fig.get_size_inches()[0] * 15.5)
    fig.text(0.01, 0.012, "\n".join(textwrap.wrap(text, width)), fontsize=8.5, color=INK2, va="bottom", ha="left", linespacing=1.35)


def ci(v, digits=2):
    return f"{v[0]:.{digits}f} to {v[1]:.{digits}f}"


