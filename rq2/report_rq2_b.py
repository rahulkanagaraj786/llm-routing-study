def curve_table(arm_key, title, allowance: str, show_bonferroni: bool):
    arm = R["arms"][arm_key]
    if allowance not in arm["by_allowance"]:
        return
    agg = arm["by_allowance"][allowance]
    w(f"### {title} — {allowance} pp target\n")
    if show_bonferroni:
        w("| k | Mean bill saved (%) | Mean accuracy lost (pp) | Mean sent to Flash (%) | "
          "t 95% loss interval (pp) | Bonferroni upper loss (pp) |")
        w("|---:|---:|---:|---:|---:|---:|")
    else:
        w("| k | Mean bill saved (%) | Mean accuracy lost (pp) | Mean sent to Flash (%) | "
          "t 95% loss interval (pp) |")
        w("|---:|---:|---:|---:|---:|")
    m0 = k0["allowances"][allowance]
    if show_bonferroni:
        w(f"| 0 (A baseline) | {m0['gross_savings_pct']:.1f} | {m0['accuracy_loss_pp']:.2f} | "
          f"{100*m0['cheap_fraction']:.1f} | — | — |")
    else:
        w(f"| 0 (A baseline) | {m0['gross_savings_pct']:.1f} | {m0['accuracy_loss_pp']:.2f} | "
          f"{100*m0['cheap_fraction']:.1f} | — |")
    for k in sorted(agg, key=int):
        row = agg[k]
        lo, hi = row["t_interval_loss_95"]
        flash = 100 * row["mean_cheap_fraction"]
        if show_bonferroni:
            w(f"| {k} | {row['mean_gross_savings_pct']:.1f} | {row['mean_accuracy_loss_pp']:.2f} | "
              f"{flash:.1f} | {lo:.2f} to {hi:.2f} | {row['t_upper_loss_bonferroni']:.2f} |")
        else:
            w(f"| {k} | {row['mean_gross_savings_pct']:.1f} | {row['mean_accuracy_loss_pp']:.2f} | "
              f"{flash:.1f} | {lo:.2f} to {hi:.2f} |")
    w("")


