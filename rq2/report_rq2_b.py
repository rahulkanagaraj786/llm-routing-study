# ---- Figures: loss and savings vs k ----
def series(arm_key, field):
    agg = R["arms"][arm_key]["by_allowance"][PA]
    ks = sorted((int(k) for k in agg), key=int)
    ys = [agg[str(k)][field] for k in ks]
    if field == "mean_accuracy_loss_pp":
        bands = [agg[str(k)]["t_interval_loss_95"] for k in ks]
    else:
        # approximate savings band from seed list
        bands = []
        for k in ks:
            seeds = agg[str(k)]["seed_gross_savings_pct"]
            import numpy as np
            from scipy import stats as st
            n = len(seeds)
            mean = float(np.mean(seeds))
            if n < 2:
                bands.append([mean, mean])
            else:
                se = float(np.std(seeds, ddof=1) / np.sqrt(n))
                t = float(st.t.ppf(0.975, n - 1))
                bands.append([mean - t * se, mean + t * se])
    return ks, ys, bands


