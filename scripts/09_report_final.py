def clean(ax, grid_axis="y"):
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.grid(axis=grid_axis, color=GRID, lw=1)
    ax.set_axisbelow(True)
    ax.tick_params(length=0)


def footer(fig, text):
    text = (TAG + ". " if TAG else "") + text
    width = int(fig.get_size_inches()[0] * 15.5)  # characters that fit at this font size
    fig.text(0.01, 0.012, "\n".join(textwrap.wrap(text, width)), fontsize=8.5, color=INK2, va="bottom", ha="left", linespacing=1.35)


def ci(b, key):
    lo, hi = b[key]
    return f"{lo:.1f} to {hi:.1f}"


